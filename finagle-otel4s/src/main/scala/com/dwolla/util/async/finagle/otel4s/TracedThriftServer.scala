package com.dwolla.util.async.finagle.otel4s

import cats.*
import cats.effect.*
import cats.effect.std.Dispatcher
import cats.effect.syntax.all.*
import cats.tagless.aop.*
import cats.tagless.implicits.*
import com.comcast.ip4s.{IpAddress, SocketAddress}
import com.dwolla.util.async.finagle.HigherKindedToMethodPerEndpoint.*
import com.dwolla.util.async.finagle.HigherKindedToMethodPerEndpoint
import com.dwolla.util.async.twitter.*
import com.twitter.finagle.*
import com.twitter.finagle.tracing.{NullTracer, Trace, TraceId}
import com.twitter.util.Future
import org.typelevel.otel4s.{Attribute, AttributeKey}
import org.typelevel.otel4s.trace.{SpanBuilder, SpanContext, SpanKind, TraceFlags, TraceState, Tracer, TracerProvider}
import scodec.bits.ByteVector

import scala.concurrent.ExecutionContext

/**
 * Starts a Finagle server that will host the given Thrift
 * method-per-endpoint implementation, tracing each request with otel4s.
 */
object TracedThriftServer {
  /**
   * The instrumentation scope name of the `Tracer` this server obtains from the `TracerProvider`.
   */
  val InstrumentationScopeName: String = "com.dwolla.util.async.finagle.otel4s"

  // The OpenTelemetry RPC semantic conventions are still in development, and otel4s only ships them
  // in its experimental semconv artifact, which this published library avoids depending on.
  private val RpcSystemName: AttributeKey[String] = AttributeKey.string("rpc.system.name")
  private val RpcMethod: AttributeKey[String] = AttributeKey.string("rpc.method")

  /**
   * Builds a `ListeningServer` that wraps each Thrift request in an otel4s `SpanKind.Server` span named
   * `{service}/{method}`, where `{service}` is the Thrift algebra's `Instrumentation#algebraName` and
   * `{method}` is the `Instrumentation#methodName`.
   *
   * The span has the attributes `rpc.system.name` (`thrift`) and `rpc.method` (the same `{service}/{method}`
   * as the span name).
   *
   * If Finagle received a `TraceId` with the request, the span continues that trace as a child of the remote
   * span that called this server; no otel4s propagator (B3 or otherwise) needs to be configured. The trace is
   * sampled unless Finagle's `TraceId` explicitly says it isn't (an undecided `TraceId` is continued as sampled).
   * Otherwise, the span is the root of a new trace.
   *
   * Finagle's own tracing is disabled on this server (`NullTracer`), so a Finagle `Tracer` registered
   * through `LoadService` doesn't record a second, duplicate server span.
   *
   * @param addr  the socket address at which to listen for connections. (Typically `0.0.0.0:port`)
   * @param label the label Finagle assigns to the server
   * @param iface the Thrift method-per-endpoint implementation. The request's server span is the current span while it runs.
   * @param ec    `ExecutionContext` where the Twitter Future is completed when the effect run by `Dispatcher#unsafeToTwitterFuture` completes
   * @tparam F      the effect in which to operate, which must have `Async[F]` and `TracerProvider[F]` instances available
   * @tparam Thrift the higher-kinded MethodPerEndpoint Thrift algebra generated by scrooge and modified by the `AddCatsTaglessInstances` scalafix
   * @return a `Resource[F, ListeningServer]` managing the lifecycle of the underlying Finagle server
   */
  def apply[F[_] : Async : TracerProvider, Thrift[_[_]] : HigherKindedToMethodPerEndpoint : Instrument](addr: SocketAddress[IpAddress],
                                                                                                         label: String,
                                                                                                         iface: Thrift[F],
                                                                                                        )
                                                                                                        (implicit ec: ExecutionContext): Resource[F, ListeningServer] =
    TracedThriftServer(addr, label, iface, identity[SpanBuilder[F]])

  /**
   * Builds a `ListeningServer` that wraps each Thrift request in an otel4s `SpanKind.Server` span named
   * `{service}/{method}`, with the `rpc.system.name` and `rpc.method` attributes. See the other overload for
   * details about the span name and attributes, how traces are continued, and about Finagle's own tracing
   * being disabled.
   *
   * @param addr          the socket address at which to listen for connections. (Typically `0.0.0.0:port`)
   * @param label         the label Finagle assigns to the server
   * @param iface         the Thrift method-per-endpoint implementation. The request's server span is the current span while it runs.
   * @param customizeSpan customizes the `SpanBuilder` for each request's span, after its name, `SpanKind.Server`, and the `rpc.system.name` and `rpc.method` attributes have been set,
   *                      so it can override any of them
   * @param ec            `ExecutionContext` where the Twitter Future is completed when the effect run by `Dispatcher#unsafeToTwitterFuture` completes
   * @tparam F      the effect in which to operate, which must have `Async[F]` and `TracerProvider[F]` instances available
   * @tparam Thrift the higher-kinded MethodPerEndpoint Thrift algebra generated by scrooge and modified by the `AddCatsTaglessInstances` scalafix
   * @return a `Resource[F, ListeningServer]` managing the lifecycle of the underlying Finagle server
   */
  def apply[F[_] : Async : TracerProvider, Thrift[_[_]] : HigherKindedToMethodPerEndpoint : Instrument](addr: SocketAddress[IpAddress],
                                                                                                         label: String,
                                                                                                         iface: Thrift[F],
                                                                                                         customizeSpan: SpanBuilder[F] => SpanBuilder[F],
                                                                                                        )
                                                                                                        (implicit ec: ExecutionContext): Resource[F, ListeningServer] =
    for {
      tracer <- TracerProvider[F].get(InstrumentationScopeName).toResource
      dispatcher <- Dispatcher.parallel[F]
      server <- Resource.make(acquire(addr, label, iface.instrument.mapK(new UnsafeInstrumentationToFuture[F](dispatcher, tracer, customizeSpan))))(release[F])
    } yield server

  /**
   * The remote parent that an incoming Finagle `TraceId` describes. A missing high half
   * of the trace ID is zero-padded, like OpenTelemetry's B3 extractor does for 64-bit IDs.
   */
  private def remoteParent(traceId: TraceId): SpanContext =
    SpanContext(
      traceId = ByteVector.fromLong(traceId.traceIdHigh.fold(0L)(_.toLong)) ++ ByteVector.fromLong(traceId.traceId.toLong),
      spanId = ByteVector.fromLong(traceId.spanId.toLong),
      traceFlags = if (traceId.sampled.contains(false)) TraceFlags.Default else TraceFlags.Sampled,
      traceState = TraceState.empty,
      remote = true,
    )

  // otel4s exports the server span itself, so Finagle's own tracer is disabled: otherwise a Tracer
  // registered through LoadService (e.g. zipkin-finagle) would be installed here and record a duplicate.
  private def acquire[F[_] : Sync, Thrift[_[_]] : HigherKindedToMethodPerEndpoint](addr: SocketAddress[IpAddress],
                                                                                   label: String,
                                                                                   iface: Thrift[Future]): F[ListeningServer] =
    Sync[F].delay {
      Thrift
        .server
        .withLabel(label)
        .withTracer(NullTracer)
        .serveIface(addr.toInetSocketAddress, iface.toMethodPerEndpoint)
    }

  private def release[F[_] : Async](s: ListeningServer): F[Unit] =
    liftFuture(Sync[F].delay(s.close()))

  private class UnsafeInstrumentationToFuture[F[_] : Sync](dispatcher: Dispatcher[F],
                                                           tracer: Tracer[F],
                                                           customizeSpan: SpanBuilder[F] => SpanBuilder[F],
                                                          )
                                                          (implicit ec: ExecutionContext) extends (Instrumentation[F, *] ~> Future) {
    override def apply[A](instrumentation: Instrumentation[F, A]): Future[A] = {
      // Finagle's TraceId is a Local-scoped context, invisible on the Dispatcher's threads,
      // so read it here on the request thread
      val maybeTraceId = Trace.idOption

      val rpcMethod = s"${instrumentation.algebraName}/${instrumentation.methodName}"

      val span =
        customizeSpan(
          tracer.spanBuilder(rpcMethod)
            .withSpanKind(SpanKind.Server)
            .addAttributes(Attribute(RpcSystemName, "thrift"), Attribute(RpcMethod, rpcMethod))
        ).build

      // with no Finagle TraceId, rootScope makes the span a root, rather than
      // a child of whatever span was current when the Dispatcher was created
      val fa = maybeTraceId.fold(tracer.rootScope(span.surround(instrumentation.value))) { traceId =>
        tracer.childScope(remoteParent(traceId))(span.surround(instrumentation.value))
      }

      dispatcher.unsafeToTwitterFuture(fa)
    }
  }

}
